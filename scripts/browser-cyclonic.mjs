import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { tours } from '../content/tours.js';
import { photos } from '../content/photos.js';
const browser = await chromium.launch({executablePath:'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe',headless:true});
const base=process.env.SITE_URL || 'http://localhost:3002';
fs.mkdirSync('qa',{recursive:true});
try {
 for(const width of [1440,390]) {
  const page=await browser.newPage({viewport:{width,height:900}});
  page.setDefaultNavigationTimeout(90000);
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('console',message=>{if(message.type()==='error')errors.push(message.text().slice(-1800));});
  await page.addInitScript(() => { window.open = (url) => { window.__qaEnquiryUrl = url; return null; }; });
  await page.goto(base,{waitUntil:'domcontentloaded'});
  await page.waitForSelector('html[data-animations-ready]');
  await page.waitForTimeout(1200);
  await page.screenshot({path:`qa/home-${width}.png`,timeout:15000});
  console.log('HOME',width,await page.evaluate(()=>({webflow:typeof window.Webflow?.require==='function',sliders:document.querySelectorAll('.w-slider-dot.w-active').length,overflow:document.documentElement.scrollWidth>innerWidth,font:getComputedStyle(document.body).fontFamily,h1:document.querySelector('h1')?.textContent})),errors);
  await page.locator('.ct-whatsapp-float').click();
  const dialog=page.locator('dialog[open]').first();
  await dialog.locator('[name=tour]').selectOption('victoria-falls-guided-tour');
  await dialog.locator('[name=name]').fill('Test Visitor');
  await dialog.locator('[name=date]').fill('2099-12-31');
  await dialog.locator('button[type=submit]').click();
  await dialog.locator('[role=status]').waitFor();
  assert.match(await dialog.locator('[role=status]').innerText(),/message is ready/);
  assert.equal(new URL(await page.evaluate(()=>window.__qaEnquiryUrl)).pathname,'/263772619171');
  await page.keyboard.press('Escape');
  const question=page.locator('.faq-question[role=button]').first();
  await question.scrollIntoViewIfNeeded();
  await question.click();
  await page.waitForTimeout(600);
  assert.equal(await question.getAttribute('aria-expanded'),'true');
  console.log('FAQ expanded height',await question.locator('..').locator('.faq-answer').evaluate(el=>el.getBoundingClientRect().height));
  await page.evaluate(()=>window.scrollTo(0,0));
  if(width===390){
    const menu=page.locator('.w-nav-button').first();
    await menu.click();
    await page.waitForFunction(() => document.querySelector('.w-nav-button')?.getAttribute('aria-expanded') === 'true');
    assert.equal(await menu.getAttribute('aria-expanded'),'true');
    console.log('MOBILE MENU passed');
  }
  await page.goto(`${base}/tours`,{waitUntil:'domcontentloaded'});
  await page.waitForSelector('html[data-ct-ready]');
  await page.waitForSelector('html[data-animations-ready]');
  await page.waitForTimeout(700);
  await page.locator('[data-filter=tours][data-value=Wildlife]').click();
  await page.waitForTimeout(300);
  console.log('FILTER',await page.locator('[data-filter=tours][data-value=Wildlife]').getAttribute('aria-pressed'),errors);
  assert.equal(await page.locator('[data-filter-list=tours] > [data-category]:visible').count(),tours.filter(t=>t.category==='Wildlife').length);
  await page.screenshot({path:`qa/tours-${width}.png`,timeout:15000});
  await page.goto(`${base}/tours/victoria-falls-guided-tour`,{waitUntil:'domcontentloaded'});
  await page.locator('.ct-inline-enquiry form').waitFor();
  await page.waitForSelector('html[data-animations-ready]');
  await page.waitForFunction(() => Number(getComputedStyle(document.querySelector('.package-slider')).opacity) > .99);
  await page.waitForTimeout(700);
  assert.equal(await page.locator('.ct-inline-enquiry [name=tour]').inputValue(),'victoria-falls-guided-tour');
  await page.screenshot({path:`qa/tour-${width}.png`,timeout:15000});
  await page.goto(`${base}/gallery`,{waitUntil:'domcontentloaded'});
  await page.waitForSelector('html[data-ct-ready]');
  await page.waitForSelector('html[data-animations-ready]');
  await page.waitForTimeout(700);
  await page.locator('[data-filter=gallery][data-value=Wildlife]').click();
  assert.equal(await page.locator('[data-filter-list=gallery] > [data-category]:visible').count(),photos.filter(p=>p.category==='Wildlife').length);
  await page.locator('[data-photo]:visible').first().click();
  assert.equal(await page.locator('dialog[open] img').count(),1);
  await page.keyboard.press('Escape');
  await page.screenshot({path:`qa/gallery-${width}.png`,timeout:15000});
  await page.goto(`${base}/contact`,{waitUntil:'domcontentloaded'});
  await page.locator('.ct-inline-enquiry form').waitFor();
  await page.waitForSelector('html[data-animations-ready]');
  await page.waitForTimeout(700);
  await page.screenshot({path:`qa/contact-${width}.png`,timeout:15000});
  await page.goto(`${base}/about`,{waitUntil:'domcontentloaded'});
  await page.waitForSelector('html[data-animations-ready]');
  await page.waitForTimeout(1500);
  await page.screenshot({path:`qa/about-${width}.png`,timeout:15000});
  console.log('Enquiry, filters, detail form, gallery lightbox and contact form passed at',width);
  console.log('Runtime errors:',errors);
  assert.equal(errors.length,0,'Browser console should be free of runtime and hydration errors');
  await page.close();
 }
}finally{await browser.close();}
